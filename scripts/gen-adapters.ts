/**
 * Collects every adapter's entry file (packages/core/src/adapters/<id>.entry.ts) into the three places that
 * list adapters, so adding an adapter adds files and edits no shared one:
 *   - packages/core/src/adapters/entries.generated.ts  (the registry, the settings rules)
 *   - the table in docs/integrations/index.md          (between the adapters:start and adapters:end markers)
 *   - docs/adapter-pages.generated.ts                  (the adapters' pages in the sidebar, docs/nav.ts)
 *   pnpm gen:adapters           write them
 *   pnpm gen:adapters --check   compare only; exit 1 when stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as prettier from "prettier";
import type { AdapterEntry } from "../packages/core/src/adapters/entry.js";
import { replaceBlock } from "./lib/marker-block.js";

const root = process.env.GEN_ADAPTERS_ROOT ?? fileURLToPath(new URL("../", import.meta.url));
const adaptersDir = join(root, "packages/core/src/adapters");
const check = process.argv.includes("--check");

const ENTRY_FILE = /^[a-z][a-z0-9-]*\.entry\.ts$/;

async function loadEntries(dir: string): Promise<{ file: string; entries: AdapterEntry[] }[]> {
  const files = readdirSync(dir)
    .filter((f) => ENTRY_FILE.test(f))
    .sort();
  const out: { file: string; entries: AdapterEntry[] }[] = [];
  for (const file of files) {
    const mod = (await import(pathToFileURL(join(dir, file)).href)) as {
      entries?: readonly AdapterEntry[];
    };
    if (!Array.isArray(mod.entries) || mod.entries.length === 0)
      throw new Error(`${file} must export \`entries\`, a non-empty array of AdapterEntry.`);
    out.push({ file, entries: [...mod.entries] });
  }
  return out;
}

const camel = (file: string): string =>
  file.replace(/\.entry\.ts$/, "").replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

function entriesModule(files: string[]): string {
  const names = files.map((f) => ({ file: f, name: camel(f) }));
  return [
    "// Generated by scripts/gen-adapters.ts (pnpm gen:adapters) from adapters/*.entry.ts. Do not edit.",
    'import type { AdapterEntry } from "./entry.js";',
    ...names.map(
      (n) => `import { entries as ${n.name} } from "./${n.file.replace(/\.ts$/, ".js")}";`,
    ),
    "",
    "export const ADAPTER_ENTRIES: readonly AdapterEntry[] = [",
    ...names.map((n) => `  ...${n.name},`),
    "];",
    "",
  ].join("\n");
}

/** The contract suite's list: one `<id>.contract.ts` in adapters/__tests__ for each entry file that has one. */
function contractsModule(files: string[]): string {
  const names = files.map((f) => ({
    file: f,
    name: camel(f.replace(/\.contract\.ts$/, ".entry.ts")),
  }));
  return [
    "// Generated by scripts/gen-adapters.ts (pnpm gen:adapters) from adapters/__tests__/*.contract.ts. Do not edit.",
    'import type { ContractEntry } from "./contract.js";',
    ...names.map(
      (n) => `import { contractEntries as ${n.name} } from "./${n.file.replace(/\.ts$/, ".js")}";`,
    ),
    "",
    "export const CONTRACT_ENTRIES: readonly ContractEntry[] = [",
    ...names.map((n) => `  ...${n.name},`),
    "];",
    "",
  ].join("\n");
}

const cell = (s: string): string => s.replace(/\|/g, "\\|");

function tableBlock(all: AdapterEntry[]): string {
  const built = all.filter((e) => e.status === "built");
  const planned = all.filter((e) => e.status === "planned");
  const row = (e: AdapterEntry): string =>
    `| ${cell(e.name)} | ${e.status === "built" ? "built" : `planned (${e.branch ?? "?"})`} | ${cell(e.docs.key)} | ${cell(e.docs.reads)} |`;
  return [
    "| Content system | Status | Key Gaugeline asks for | What it reads |",
    "| --- | --- | --- | --- |",
    ...[...built, ...planned].map(row),
  ].join("\n");
}

function pagesModule(all: AdapterEntry[]): string {
  const pages = all.flatMap((e) => (e.page ? [e.page] : []));
  return [
    "// Generated by scripts/gen-adapters.ts (pnpm gen:adapters) from adapters/*.entry.ts. Do not edit.",
    "",
    "export const ADAPTER_PAGES: { slug: string; title: string }[] = [",
    ...pages.map(
      (p) => `  { slug: ${JSON.stringify(p.slug)}, title: ${JSON.stringify(p.title)} },`,
    ),
    "];",
    "",
  ].join("\n");
}

async function format(path: string, text: string): Promise<string> {
  const config = (await prettier.resolveConfig(path)) ?? {};
  return prettier.format(text, { ...config, filepath: path });
}

async function main(): Promise<number> {
  const loaded = await loadEntries(adaptersDir);
  const all = loaded.flatMap((l) => l.entries);
  const ids = all.map((e) => e.id);
  const dup = ids.find((id, i) => ids.indexOf(id) !== i);
  if (dup) {
    process.stderr.write(`gen:adapters: two entries have the id "${dup}".\n`);
    return 1;
  }
  const targets: { path: string; text: string }[] = [
    {
      path: join(adaptersDir, "entries.generated.ts"),
      text: await format(
        join(adaptersDir, "entries.generated.ts"),
        entriesModule(loaded.map((l) => l.file)),
      ),
    },
    {
      path: join(adaptersDir, "__tests__/contracts.generated.ts"),
      text: await format(
        join(adaptersDir, "__tests__/contracts.generated.ts"),
        contractsModule(
          readdirSync(join(adaptersDir, "__tests__"))
            .filter((f) => /^[a-z][a-z0-9-]*\.contract\.ts$/.test(f))
            .sort(),
        ),
      ),
    },
    {
      path: join(root, "docs/adapter-pages.generated.ts"),
      text: await format(join(root, "docs/adapter-pages.generated.ts"), pagesModule(all)),
    },
  ];
  const indexPath = join(root, "docs/integrations/index.md");
  const index = readFileSync(indexPath, "utf8");
  const wrapped = replaceBlock(index, "adapters", tableBlock(all));
  if (!wrapped.ok) {
    process.stderr.write(`gen:adapters: ${indexPath}: ${wrapped.error}\n`);
    return 1;
  }
  // prettier aligns the table, so the comparison is made on the formatted file.
  targets.push({ path: indexPath, text: await format(indexPath, wrapped.text) });

  let stale = 0;
  for (const t of targets) {
    const current = existsSync(t.path) ? readFileSync(t.path, "utf8").replace(/\r\n/g, "\n") : "";
    if (current === t.text) continue;
    if (check) {
      stale += 1;
      process.stderr.write(`gen:adapters: ${t.path} is stale. Run pnpm gen:adapters.\n`);
    } else writeFileSync(t.path, t.text);
  }
  return stale > 0 ? 1 : 0;
}

process.exitCode = await main();
