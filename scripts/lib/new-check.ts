import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export const AREA_SLUGS = {
  search: "Search & sharing",
  visitors: "Visitors",
  sales: "Sales & prices",
  leads: "Leads",
  security: "Security & email",
  launch: "Launch day",
} as const;
export type AreaSlug = keyof typeof AREA_SLUGS;
export const SEVERITY_VALUES = ["high", "medium", "low"] as const;
export type Severity = (typeof SEVERITY_VALUES)[number];

export interface RepoState {
  /** Ids registered in packages/core/src/checks/index.ts. */
  registered: string[];
  /** Ids in docs/check-ids.lock.json (everything that ever shipped). */
  locked: string[];
  /** Paths (relative to the root) that already exist. */
  files: Set<string>;
  /** Current text of packages/core/src/checks/index.ts. */
  indexSource: string;
}

/** create: a new file. append: the existing file with the new entry added in its sorted place. */
export type Plan = { path: string; action: "create" | "append"; content: string }[];

export const INDEX_PATH = "packages/core/src/checks/index.ts";
export const LOCK_PATH = "docs/check-ids.lock.json";
const KEBAB = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function camel(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** The generated block of index.ts, rebuilt from a sorted list of ids. */
export function renderIndexBlock(ids: string[]): string {
  const sorted = [...new Set(ids)].sort();
  return [
    "// checks:start (generated by pnpm new:check: imports and registrations, sorted by id)",
    ...sorted.map((id) => `import { ${camel(id)} } from "./${id}.js";`),
    "",
    "/** Page checks in registration order (sorted by id): within a severity, findings follow this order. */",
    "export const PAGE_CHECKS = [",
    ...sorted.map((id) => `  ${camel(id)},`),
    "] as const;",
    "// checks:end",
  ].join("\n");
}

export function registeredIds(indexSource: string): string[] {
  return [...indexSource.matchAll(/^import \{ \w+ \} from "\.\/([a-z0-9-]+)\.js";$/gm)].map(
    (m) => m[1] ?? "",
  );
}

const ts = (s: string) => JSON.stringify(s);

function checkFile(id: string, area: string, severity: Severity, title: string): string {
  return `import { defineCheck } from "../model.js";
import type { PageSnapshot } from "../snapshot.js";

/** The scaffold's rule: replace it, and the TODO text below, before this can merge. */
const SCAFFOLD_TITLE = ${ts(`Failing page for ${id}`)};

export const ${camel(id)} = defineCheck<PageSnapshot>({
  id: ${ts(id)},
  area: ${ts(area)},
  severity: ${ts(severity)},
  title: ${ts(title)},
  what: "TODO: what this check catches, in one sentence.",
  why: "TODO: why it matters to whoever owns the site.",
  fix: "TODO: how to fix it.",
  tech: "TODO: the technical line for whoever fixes it",
  run(page) {
    if (page.title !== SCAFFOLD_TITLE) return [];
    return [
      {
        checkId: ${ts(id)},
        severity: ${ts(severity)},
        title: this.title,
        evidence: \`title is "\${page.title}" on \${page.finalUrl}\`,
        url: page.finalUrl,
      },
    ];
  },
});
`;
}

function testFile(id: string, severity: Severity, title: string): string {
  return `import { describe, expect, it } from "vitest";
import { ${camel(id)} } from "../${id}.js";
import { URL0, ctx, page } from "./helpers.js";

describe(${ts(id)}, () => {
  it("passes on a page without the problem", async () => {
    expect(await ${camel(id)}.run(page(), ctx)).toEqual([]);
  });

  it("fails on a page with it, with the exact evidence", async () => {
    expect(await ${camel(id)}.run(page({ title: ${ts(`Failing page for ${id}`)} }), ctx)).toEqual([
      {
        checkId: ${ts(id)},
        severity: ${ts(severity)},
        title: ${ts(title)},
        evidence: ${ts(`title is "Failing page for ${id}" on `)} + URL0,
        url: URL0,
      },
    ]);
  });
});
`;
}

const html = (title: string) =>
  `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<title>${title}</title>\n<link rel="canonical" href="/">\n</head>\n<body>\n<main>\n<h1>${title}</h1>\n<p>An invented page for the scaffold of this check. Replace it with a page that shows the problem.</p>\n</main>\n</body>\n</html>\n`;

/** Everything the new check needs, as a value. Touches no disk. */
export function planNewCheck(
  opts: { id: string; area: string; severity: string; title?: string },
  repo: RepoState,
): Plan {
  const { id } = opts;
  if (!KEBAB.test(id))
    throw new Error(`Check id "${id}" must be kebab-case, for example "canonical-elsewhere".`);
  if (!(opts.area in AREA_SLUGS)) {
    throw new Error(
      `Unknown area "${opts.area}". Use one of: ${Object.keys(AREA_SLUGS).join(", ")}.`,
    );
  }
  if (!SEVERITY_VALUES.includes(opts.severity as Severity)) {
    throw new Error(
      `Unknown severity "${opts.severity}". Use one of: ${SEVERITY_VALUES.join(", ")}.`,
    );
  }
  if (repo.registered.includes(id)) throw new Error(`A check with the id "${id}" already exists.`);
  if (repo.locked.includes(id)) {
    throw new Error(
      `"${id}" belonged to a retired check. Ids are never reused: old suppressions and CI configs name it.`,
    );
  }
  const area = AREA_SLUGS[opts.area as AreaSlug];
  const severity = opts.severity as Severity;
  const title = opts.title ?? `TODO: plain-English title for ${id}`;
  const creates: Plan = [
    {
      path: `packages/core/src/checks/${id}.ts`,
      action: "create",
      content: checkFile(id, area, severity, title),
    },
    {
      path: `packages/core/src/checks/__tests__/${id}.test.ts`,
      action: "create",
      content: testFile(id, severity, title),
    },
    {
      path: `packages/fixtures/sites/${id}/index.html`,
      action: "create",
      content: html(`Failing page for ${id}`),
    },
    {
      path: `packages/fixtures/sites/${id}/clean.html`,
      action: "create",
      content: html(`Clean page for ${id}`),
    },
    { path: `packages/fixtures/sites/${id}/routes.json`, action: "create", content: "{}\n" },
    {
      path: `.changeset/${id}.md`,
      action: "create",
      content: `---\n"gaugeline": minor\n---\n\nNew check: ${title.replace(/\.$/, "")}.\n`,
    },
  ];
  const clash = creates.find((c) => repo.files.has(c.path));
  if (clash) throw new Error(`${clash.path} already exists. Nothing was written.`);
  const block = /\/\/ checks:start[\s\S]*?\/\/ checks:end/;
  if (!block.test(repo.indexSource))
    throw new Error(`${INDEX_PATH} has no "// checks:start" ... "// checks:end" block.`);
  const index = repo.indexSource.replace(block, renderIndexBlock([...repo.registered, id]));
  const lock = `${JSON.stringify([...new Set([...repo.locked, id])].sort(), null, 2)}\n`;
  return [
    creates[0]!,
    creates[1]!,
    creates[2]!,
    creates[3]!,
    creates[4]!,
    { path: INDEX_PATH, action: "append", content: index },
    creates[5]!,
    { path: LOCK_PATH, action: "append", content: lock },
  ];
}

/** Write a plan. Creates refuse to overwrite (flag wx); appends replace the file with its new content. */
export function applyPlan(plan: Plan, root: string): void {
  for (const step of plan) {
    if (step.action === "create" && existsSync(join(root, step.path)))
      throw new Error(`${step.path} already exists.`);
  }
  for (const step of plan) {
    const full = join(root, step.path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, step.content, { flag: step.action === "create" ? "wx" : "w" });
  }
}

export function readRepoState(root: string, paths: string[]): RepoState {
  const indexSource = readFileSync(join(root, INDEX_PATH), "utf8");
  return {
    registered: registeredIds(indexSource),
    locked: existsSync(join(root, LOCK_PATH))
      ? (JSON.parse(readFileSync(join(root, LOCK_PATH), "utf8")) as string[])
      : [],
    files: new Set(paths.filter((p) => existsSync(join(root, p)))),
    indexSource,
  };
}

/** The workspace root: the nearest folder above `from` with a pnpm-workspace.yaml. */
export function findRoot(from: string): string {
  let dir = from;
  for (;;) {
    if (existsSync(join(dir, "pnpm-workspace.yaml"))) return dir;
    const up = dirname(dir);
    if (up === dir)
      throw new Error("Run this inside the Gaugeline workspace (no pnpm-workspace.yaml found).");
    dir = up;
  }
}

/** The six places a check lives, for printing: the fixture's three files are one folder. */
export function places(plan: Plan): string[] {
  const out: string[] = [];
  for (const step of plan) {
    const fixture = /^(packages\/fixtures\/sites\/[^/]+\/)/.exec(step.path)?.[1];
    const place = fixture ?? step.path;
    if (!out.includes(place)) out.push(place);
  }
  return out;
}
