export interface ChangelogEntry {
  version: string;
  /** yyyy-mm-dd from the release tag, or null before the version is tagged. */
  date: string | null;
  headline: string | null;
  items: string[];
}

const SECTION_ORDER = ["major", "minor", "patch"] as const;

/** Parse a Changesets CHANGELOG.md into entries, newest first. */
export function parseChangelog(markdown: string): Omit<ChangelogEntry, "date">[] {
  const entries: Omit<ChangelogEntry, "date">[] = [];
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  let current:
    { version: string; headline: string | null; sections: Record<string, string[]> } | undefined;
  let section = "patch";
  let item: string[] | undefined;
  const flushItem = () => {
    if (current && item) {
      const text = item.join(" ").replace(/\s+/g, " ").trim();
      if (/^Headline:/i.test(text)) current.headline = text.replace(/^Headline:\s*/i, "");
      else if (text !== "" && !text.startsWith("(internal)"))
        (current.sections[section] ??= []).push(text);
    }
    item = undefined;
  };
  const flushEntry = () => {
    flushItem();
    if (current) {
      entries.push({
        version: current.version,
        headline: current.headline,
        items: SECTION_ORDER.flatMap((s) => current?.sections[s] ?? []),
      });
    }
  };
  for (const line of lines) {
    const version = /^## (\d+\.\d+\.\d+\S*)\s*$/.exec(line);
    if (version) {
      flushEntry();
      current = { version: version[1] ?? "", headline: null, sections: {} };
      section = "patch";
      continue;
    }
    const heading = /^### (Major|Minor|Patch) Changes/i.exec(line);
    if (heading) {
      flushItem();
      section = (heading[1] ?? "patch").toLowerCase();
      continue;
    }
    const bullet = /^- (?:[0-9a-f]{7,40}: )?(.*)$/.exec(line);
    if (bullet && current) {
      flushItem();
      item = [bullet[1] ?? ""];
      continue;
    }
    if (item && /^\s+\S/.test(line)) item.push(line.trim());
    else if (line.trim() === "") flushItem();
  }
  flushEntry();
  return entries.sort((a, b) => compareVersions(b.version, a.version));
}

export function compareVersions(a: string, b: string): number {
  const pa = a.split(/[.-]/).map((x) => Number.parseInt(x, 10) || 0);
  const pb = b.split(/[.-]/).map((x) => Number.parseInt(x, 10) || 0);
  for (let i = 0; i < 3; i++) {
    const d = (pa[i] ?? 0) - (pb[i] ?? 0);
    if (d !== 0) return d;
  }
  return 0;
}

/** Generated entries plus hand-backfilled ones the changelog does not have, newest first. */
export function mergeEntries(
  generated: ChangelogEntry[],
  backfill: ChangelogEntry[],
): ChangelogEntry[] {
  const seen = new Set(generated.map((e) => e.version));
  return [...generated, ...backfill.filter((e) => !seen.has(e.version))].sort((a, b) =>
    compareVersions(b.version, a.version),
  );
}

/** docs/changelog.md: date, version, headline, bullets. Versions with no user-facing items are skipped. */
export function renderChangelogPage(entries: ChangelogEntry[]): string {
  const out = [
    "# Changelog",
    "",
    "<!-- Generated by pnpm docs:changelog from packages/cli/CHANGELOG.md and docs/changelog.backfill.json. Do not edit. -->",
    "",
  ];
  for (const e of entries) {
    if (e.items.length === 0) continue;
    out.push(
      `## ${e.version}${e.headline ? `: ${e.headline}` : ""}`,
      "",
      e.date ? `Released ${e.date}.` : "Not released yet.",
      "",
    );
    for (const i of e.items) out.push(`- ${i}`);
    out.push("");
  }
  return out.join("\n");
}
