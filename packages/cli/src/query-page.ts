import {
  ConfigError,
  SANITY_DATASET,
  SANITY_PROJECT_ID,
  SANITY_TOKEN,
  createFetcher,
  freezeEnv,
  readSchemaFileFull,
  readShapeForType,
  scaffoldRoute,
  type FetcherOptions,
  type Outcome,
} from "@gaugeline/core";
import { basename } from "node:path";
import { schemaPath } from "./query-schema.js";
import { inspectScaffold, writeScaffold, type ScaffoldFs } from "./scaffold-write.js";

interface Out {
  stdout: { write(s: string): unknown };
  stderr: { write(s: string): unknown };
  env?: Record<string, string | undefined>;
}

interface Deps {
  cwd: string;
  fetcher?: FetcherOptions;
  /** Tests: the file system the three files are written with. */
  fs?: ScaffoldFs;
}

/**
 * gaugeline query --page --type <name> --out <folder>: write queries.ts, types.ts and page.tsx for
 * a route into a folder of the user's own project, from the shape of the type's published
 * documents. The shape is read as for --suggest: field names and kinds from the schema file
 * (--schema, or ./schema.json), how common each is from count queries, one GET, drafts left out;
 * no document and no value is requested. The files are generated by templates in core
 * (`scaffoldRoute`, no model, no I/O) and written here, all three or none, into a folder inside the
 * working directory, never over a file that exists unless --force, and every path written is
 * printed. Nothing is sent to the dataset and no git command is run. Everything that can be refused
 * is refused before the first request. A type with no published documents, or one the schema does
 * not declare, is exit 2 and creates nothing, not even the folder.
 */
export async function runPage(
  args: {
    page: { type: string; out: string; force: boolean };
    schema?: string;
    allowPrivate?: boolean;
    quiet?: boolean;
  },
  io: Out,
  deps: Deps,
): Promise<Outcome> {
  const { type, out, force } = args.page;
  const target = { force, cwd: deps.cwd, ...(deps.fs ? { fs: deps.fs } : {}) };
  // Where the files would go, and whether they can: checked before anything is asked or written.
  await inspectScaffold(
    [{ name: "queries.ts" }, { name: "types.ts" }, { name: "page.tsx" }],
    out,
    target,
  );
  if ((io.env?.[SANITY_PROJECT_ID] ?? "").trim() === "")
    throw new ConfigError(
      "gaugeline query --page counts the published documents of a type in your dataset, and that needs SANITY_PROJECT_ID.",
      {
        hint: "Set SANITY_PROJECT_ID (and SANITY_TOKEN, with the Viewer role, for a private dataset).",
      },
    );
  const schema = await readSchemaFileFull(
    await schemaPath(deps.cwd, ".", args.schema, "--page"),
    "Writing a route",
  );
  const run = await readShapeForType({
    type,
    schema,
    env: freezeEnv(io.env ?? {}, [SANITY_PROJECT_ID, SANITY_DATASET, SANITY_TOKEN]),
    fetcher: createFetcher({
      ...deps.fetcher,
      ...(args.allowPrivate === true ? { allowPrivate: true } : {}),
    }),
  });
  if (args.quiet !== true) for (const n of run.notices) io.stderr.write(`${n}\n`);
  if (run.shape.sampled === 0)
    throw new ConfigError(
      `Nothing of type ${run.shape.type} exists in the published documents of the dataset "${run.dataset}", so nothing was written.`,
      {
        hint: "Check the type name against your Studio schema (it is case-sensitive), and that the documents are published, not only drafts.",
      },
    );
  const files = scaffoldRoute(run.shape);
  await writeScaffold(files, out, target);

  // The folder as it was typed, with Windows separators and a trailing slash left alone but not doubled.
  const shown = out.replace(/[\\/]+$/, "") || ".";
  const folder = basename(shown);
  if (args.quiet !== true && /^\[.+\]$/.test(folder) && folder !== "[slug]")
    io.stderr.write(
      `The page reads params.slug, and this folder is ${folder}: rename the folder to [slug], or change the name in page.tsx and queries.ts.\n`,
    );
  const documents = run.shape.sampled === 1 ? "document" : "documents";
  io.stdout.write(
    [
      `Wrote ${files.length} files to ${shown} from ${run.shape.sampled} published ${run.shape.type} ${documents}`,
      ...files.map((f) => `  ${shown}/${f.name}`),
      "",
    ].join("\n"),
  );
  return { kind: "ran", highFindings: 0, drift: false };
}
