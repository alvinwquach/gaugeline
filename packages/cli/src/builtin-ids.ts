/**
 * Every check Gaugeline ships, in one registry, whichever flag adds it to a run: the ids a check of your
 * own may never take (see registerCustomChecks). The same list scripts/gen-checks.ts builds the checks
 * reference from; a test fails when an id in docs/check-ids.lock.json is missing here.
 */
export function builtInCheckIds(): Set<string> {
  const groups: ReadonlyArray<ReadonlyArray<{ id: string }>> = [
    PLAN_CHECKS,
    PRINTED_CHECKS,
    CAMPAIGN_CHECKS,
    AD_LANDING_CHECKS,
    DUPLICATE_CHECKS,
    EMAIL_CHECKS,
    RENEWALS_CHECKS,
    HANDOFF_CHECKS,
    COST_CHECKS,
    TRACKER_CHECKS,
    PUBLISHED_CHECKS,
    BACKUPS_CHECKS,
    LIBRARY_CHECKS,
    WORDPRESS_CHECKS,
    PRESENCE_CHECKS,
    PRICE_CHECKS,
    SUBSCRIPTION_CHECKS,
    QUERY_CHECKS,
    QUERY_DUPE_CHECKS,
    QUERY_GENERATED_CHECKS,
    QUERY_UNUSED_CHECKS,
    MUTATION_CHECKS,
    GRAPHQL_CHECKS,
    RECEIPT_CHECKS,
    ROUTE_CHECKS,
    WEBHOOK_CHECKS,
    CUTOVER_ONLY_CHECKS,
    MIGRATION_CHECKS,
    WEBFLOW_CHECKS,
    SHOPIFY_CHECKS,
    CONTENTFUL_CHECKS,
    SQUARESPACE_COMMERCE_CHECKS,
    STRAPI_CHECKS,
    CRAFT_CHECKS,
    HYGRAPH_CHECKS,
    UMBRACO_CHECKS,
    SITECORE_CHECKS,
    JOOMLA_CHECKS,
    DATOCMS_CHECKS,
    PRISMIC_CHECKS,
    DIRECTUS_CHECKS,
    DRUPAL_CHECKS,
    PAYLOAD_CHECKS,
    KONTENT_AI_CHECKS,
    HUBSPOT_CMS_CHECKS,
    PAYLOAD_CHECKS,
    SUPABASE_PLATFORM_CHECKS,
    STATIC_CHECKS,
  ];
  return new Set([
    ...createPageRegistry()
      .all()
      .map((c) => c.id),
    ...groups.flatMap((g) => g.map((c) => c.id)),
  ]);
}
