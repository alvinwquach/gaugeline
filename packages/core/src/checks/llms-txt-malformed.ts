import { defineCheck } from "../model.js";
import type { PageSnapshot } from "../snapshot.js";

/** An llms.txt larger than this belongs in llms-full.txt: assistants read the short file first. */
export const LLMS_TXT_MAX_CHARS = 200_000;

export const llmsTxtMalformed = defineCheck<PageSnapshot>({
  id: "llms-txt-malformed",
  size: "S",
  done: "llms.txt has a title, at least one section of links, and stays a short guide.",
  estimateChanges: "A llms.txt generated by a plugin is fixed in the plugin's settings.",
  area: "Search & sharing",
  severity: "low",
  title: "Your llms.txt is not in the format assistants expect",
  what: "/llms.txt exists but has no # title, no ## section with a list of links, or is so large it is no longer a short guide.",
  why: "llms.txt is meant to be a short Markdown guide to your most useful pages. A file an assistant cannot parse into a title and links is ignored or misread.",
  fix: "Start with one # line naming the business, optionally a > summary, then ## sections of - [Page](https://...): note lines. Put long text in llms-full.txt.",
  tech: "/llms.txt (2xx, not HTML) has no H1, or no H2 section with a Markdown link list item, or is over 200000 characters; an HTML 200 counts as missing",
  async run(_page, ctx) {
    const site = await ctx.site?.();
    const llms = site?.llms;
    if (!site || !llms || llms.state !== "found" || !llms.file) return [];
    if (llms.truncated) {
      // Part of the file was not read: say nothing about its format.
      ctx.couldNotCheck?.(llms.url, "llms.txt was longer than the size Gaugeline reads");
      return [];
    }
    const file = llms.file;
    const links = file.sections.reduce((n, s) => n + s.links.length, 0);
    const problems: string[] = [];
    if (file.text.trim() === "") problems.push("the file is empty");
    else {
      if (!file.title) problems.push("no # title line");
      if (file.sections.length === 0) problems.push("no ## sections");
      else if (links === 0) problems.push("no section has a link list (- [Title](url))");
    }
    if (file.text.length > LLMS_TXT_MAX_CHARS)
      problems.push(`${file.text.length} characters is too long for a short guide`);
    if (problems.length === 0) return [];
    return [
      {
        checkId: "llms-txt-malformed",
        severity: "low",
        title: this.title,
        evidence: `${llms.url}: ${problems.join("; ")}`,
        url: llms.url,
      },
    ];
  },
});
