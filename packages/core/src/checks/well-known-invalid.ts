import { defineCheck } from "../model.js";
import type { PageSnapshot } from "../snapshot.js";
import { readWellKnown } from "../well-known.js";

export const wellKnownInvalid = defineCheck<PageSnapshot>({
  id: "well-known-invalid",
  size: "S",
  done: "Every agent discovery file the site serves is a valid JSON object.",
  estimateChanges: "A file generated by a plugin is fixed at the source.",
  area: "Search & sharing",
  severity: "low",
  title: "An agent discovery file on your site is broken",
  what: "The site serves one of the standard /.well-known/ files AI agents look for (an agent card, an OAuth resource description or a legacy plugin manifest), and it is not valid JSON.",
  why: "Agents read these files to learn what the site offers and how to sign in. A file that does not parse is skipped, or breaks the agent's setup.",
  fix: "Fix the JSON, or remove the file if it is no longer used. A site with none of these files has nothing to fix: they are optional.",
  tech: "GET of each path in packages/core/src/data/well-known.json answers 2xx with a non-HTML body that does not parse as a JSON object; 404, HTML and 5xx answers mean no file",
  async run(page, ctx) {
    if (!ctx.fetcher) return [];
    const reads = await readWellKnown(ctx.fetcher, new URL(page.finalUrl).origin);
    for (const r of reads.filter((x) => x.state === "unread")) {
      ctx.couldNotCheck?.(r.url, "the file was larger than Gaugeline reads");
    }
    const bad = reads.filter((r) => r.state === "invalid");
    return bad.map((r) => ({
      checkId: "well-known-invalid",
      severity: "low" as const,
      title: this.title,
      evidence: `${r.path} (${r.name}) ${r.why ?? "is invalid"}`,
      url: r.url,
    }));
  },
});
