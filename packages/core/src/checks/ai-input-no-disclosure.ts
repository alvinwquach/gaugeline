import { findAiInputFlows, hasDisclosure, type Flow } from "../ai-disclosure/flows.js";
import { defineCheck } from "../model.js";
import type { PageSnapshot } from "../snapshot.js";
import { escapeInvisible } from "./hidden-text/escape.js";
import { isHtmlPage } from "./page.js";

function describe(flow: Flow, path: string): string {
  switch (flow.how) {
    case "form":
      return `a form on ${path} sends what a visitor types to ${flow.host}`;
    case "script":
      return `a script on ${path} sends what a visitor types to ${flow.host}`;
    case "widget":
      return `the ${flow.label} AI assistant widget loads on ${path}`;
  }
}

/**
 * AI-13. A visitor who types into a box that sends their words to an AI service should be told an AI is on the other end.
 * The check finds where input goes from the page itself (a form whose action is an AI provider's host, an AI assistant
 * widget, a script that names an AI host on a page with a field to type into) and looks for words that say an AI or a bot
 * answers. It does not say what a law requires; that is for the business and its own counsel. It reads the page and
 * the same-site script files the run already read, sends no request, and prints no page text.
 *
 * // [docs] uncited: the providers' API hosts and the vendors' hosts are from memory (their sites were unreachable when this was written).
 */
export const aiInputNoDisclosure = defineCheck<PageSnapshot>({
  id: "ai-input-no-disclosure",
  size: "S",
  done: "Wherever a visitor can type to an AI, the page says in plain words that an AI answers, near the box or in its label.",
  estimateChanges:
    "One sentence next to the box or in its placeholder. Deciding what it should say, and whether the privacy notice needs a line, is a conversation with the client and their own counsel.",
  area: "Security & email",
  severity: "medium",
  title: "Visitors can type to an AI service and the page does not say so",
  what: "What a visitor types into a form, a chat box or an assistant on this page goes to an AI service run by another company, and nothing on the page says that an AI or a bot is answering. Gaugeline names where the input goes and says it found no such words.",
  why: "People type different things to a person and to a machine, and many will want to know who else sees it. Whether a notice is required where a business operates is a question for the client and their own counsel; Gaugeline does not say. Telling visitors is cheap and is what most of them would expect.",
  fix: 'Say it in plain words next to the box or in its placeholder, for example "Answers here come from an AI assistant and may be wrong", and check the privacy notice mentions that what visitors type is sent to the AI provider.',
  tech: "Three kinds of flow, from the page's own HTML and scripts: a form whose action is the API host of a model provider (a fixed list of 15 hosts in packages/core/src/ai-disclosure/flows.ts); an AI assistant widget from the vendors table of ai-widget-inventory (those marked ai); and a script (inline, or one of up to 15 same-site script files) that writes a provider's host as an address while the page has a textarea or a text input. A disclosure is any of a fixed list of phrases (AI, artificial intelligence, chatbot, virtual or automated assistant, language model, generated by an AI, powered by a named model, bot) in the page's visible text, a placeholder, an aria-label, a title or an image alt; text in scripts, styles, templates and comments is not read. A page with a flow and none of the phrases is one medium finding naming the hosts and widgets, never page text, a field or a query. A flow built at run time from parts of an address, one on another page, or one inside a widget's own frame is not seen. The hosts are from memory (uncited). No request is made",
  async run(page, ctx) {
    if (!isHtmlPage(page)) return [];
    const files = (await ctx.scripts?.()) ?? [];
    const flows = findAiInputFlows(
      page,
      files.map((f) => f.text),
    );
    if (flows.length === 0 || hasDisclosure(page)) return [];
    const path = escapeInvisible(new URL(page.finalUrl).pathname, 120);
    return [
      {
        checkId: "ai-input-no-disclosure",
        severity: "medium",
        title: this.title,
        evidence: `${flows.map((f) => describe(f, path)).join(", and ")}, and nothing on the page says an AI answers`,
        url: page.finalUrl,
      },
    ];
  },
});
