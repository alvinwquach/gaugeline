import { load } from "cheerio/slim";
import { findAiWidgets } from "../ai-widgets/vendors.js";
import type { PageSnapshot } from "../snapshot.js";

/**
 * Where what a visitor types goes, and whether the page says an AI is answering (AI-13). Plain rules over the page's
 * own HTML and scripts: no request, no model, the same page gives the same answer.
 *
 * The hosts are the public API hosts of model providers, from memory (uncited: the providers' sites were unreachable
 * when this was written). The words that count as telling a visitor are a fixed list below.
 */
export const AI_API_HOSTS: readonly string[] = Object.freeze([
  "api-inference.huggingface.co",
  "api.cohere.ai",
  "api.cohere.com",
  "api.deepseek.com",
  "api.fireworks.ai",
  "api.groq.com",
  "api.mistral.ai",
  "api.openai.com",
  "api.perplexity.ai",
  "api.replicate.com",
  "api.together.xyz",
  "api.x.ai",
  "generativelanguage.googleapis.com",
  "openrouter.ai",
  "router.huggingface.co",
]);

export type Flow =
  | { how: "form"; host: string }
  | { how: "widget"; label: string }
  | { how: "script"; host: string };

const escape = (host: string): string => host.replace(/\./g, "\\.");

/** An AI host written in a script as an address: the whole host, so a look-alike that only starts with it is not one. */
const HOST_IN_SCRIPT = new RegExp(
  `//(${AI_API_HOSTS.map(escape).join("|")})(?=[/:?#"'\`\\s)\\\\]|$)`,
  "gi",
);

/** The host of an http(s) address, lower case, or undefined. */
function hostOf(address: string | undefined): string | undefined {
  if (address === undefined) return undefined;
  try {
    const url = new URL(address.startsWith("//") ? `https:${address}` : address);
    return url.protocol === "https:" || url.protocol === "http:"
      ? url.hostname.toLowerCase()
      : undefined;
  } catch {
    return undefined;
  }
}

const isAiHost = (host: string): boolean => AI_API_HOSTS.includes(host);

/** Field types that send nothing a visitor typed. */
const NOT_TEXT = new Set([
  "hidden",
  "checkbox",
  "radio",
  "submit",
  "button",
  "image",
  "file",
  "reset",
  "range",
  "color",
]);

/** True when the page has a field a visitor can type into (a textarea, or an input that takes text). */
function hasTextInput(page: PageSnapshot): boolean {
  const $ = load(page.hops.at(-1)?.body ?? "");
  return $("textarea, input")
    .toArray()
    .some((el) => {
      if (el.tagName === "textarea") return true;
      return !NOT_TEXT.has(($(el).attr("type") ?? "text").trim().toLowerCase());
    });
}

/**
 * Where what a visitor types goes on this page, at most one entry per kind and host, in this order: a form whose
 * action is an AI host, an AI assistant widget the page loads (the vendors in ai-widgets), and a script (inline, or one
 * of `scriptTexts`, the page's same-site script files) that names an AI host while the page has a field to type into.
 */
export function findAiInputFlows(page: PageSnapshot, scriptTexts: readonly string[] = []): Flow[] {
  const out: Flow[] = [];
  const seen = new Set<string>();
  const add = (flow: Flow, key: string): void => {
    if (seen.has(key)) return;
    seen.add(key);
    out.push(flow);
  };
  for (const form of page.forms) {
    const host = hostOf(form.action);
    if (host !== undefined && isAiHost(host)) add({ how: "form", host }, `form:${host}`);
  }
  for (const w of findAiWidgets(page))
    if (w.ai) add({ how: "widget", label: w.label }, `widget:${w.id}`);
  const texts = [
    ...(page.scriptTags ?? []).flatMap((t) => (t.inline === undefined ? [] : [t.inline])),
    ...scriptTexts,
  ];
  const hosts: string[] = [];
  for (const text of texts)
    for (const m of text.matchAll(HOST_IN_SCRIPT)) hosts.push((m[1] ?? "").toLowerCase());
  if (hosts.length > 0 && hasTextInput(page))
    for (const host of hosts) add({ how: "script", host }, `script:${host}`);
  return out;
}

/**
 * Words that tell a visitor an AI or a bot is answering. Fixed and bounded. A stricter or looser list is a decision for
 * a later branch; this one is deliberately generous, because a missing disclosure is only flagged when none of them is there.
 */
const DISCLOSURE =
  /\b(?:AI|A\.I\.)(?![A-Za-z])|\bartificial intelligence\b|\bchat ?bots?\b|\b(?:virtual|digital|automated|AI) (?:assistants?|agents?|helpers?)\b|\bautomated (?:replies|reply|answers?|responses?|chat)\b|\blanguage models?\b|\bmachine[- ]generated\b|\bgenerated by (?:an? )?(?:AI|model|machine)\b|\bpowered by (?:openai|chatgpt|gpt|gemini|AI)\b|\bbot\b/i;

/** The most text read for the words: a page is not a book. */
const TEXT_MAX = 500_000;

/**
 * True when the page's visible text, or a placeholder, aria-label, title or image alt, says an AI or a bot is answering.
 * Text in scripts, styles, templates and comments is not read: a visitor never sees it.
 */
export function hasDisclosure(page: PageSnapshot): boolean {
  const $ = load(page.hops.at(-1)?.body ?? "");
  $("script, style, noscript, template").remove();
  // Neighbouring elements are separate words: "<title>T</title><p>Powered by" must not read as "TPowered by".
  $("*").before(" ").after(" ");
  const attrs = $("[placeholder], [aria-label], [title], img[alt]")
    .toArray()
    .flatMap((el) => ["placeholder", "aria-label", "title", "alt"].map((a) => $(el).attr(a) ?? ""))
    .join(" ");
  return DISCLOSURE.test(`${$.root().text().slice(0, TEXT_MAX)} ${attrs.slice(0, TEXT_MAX)}`);
}
